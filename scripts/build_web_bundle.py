"""TASK 5B.1a — build the self-contained, offline-capable web bundle.

Writes ``web_simulator/data/embedded_bundle.js`` defining ``window.MODEL_BUNDLE``:

  * the full model metadata (grid, SG quadrature weights, physical constants,
    in-distribution / slider ranges, and the 8 verified SG/FV preset states with
    their ground-truth 2D fields),
  * base64-inlined ONNX binaries for both operators (no ``fetch`` → works under
    ``file://``),
  * base64-inlined float32 PyTorch weights + shapes for the pure-JS fallback
    engine (``web_simulator/engine_js.js``).

Also writes ``web_simulator/data/js_engine_reference.json`` with ONNX reference
outputs for a set of probe parameters, used by the Node DOM harness
(``scripts/test_web_simulator_dom.js``) to prove the JS engine matches Python to
< 1e-5.  Local only; no paid calls.
"""

import base64
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from operators.constants import (  # noqa: E402
    A_LAMBDA_M2,
    DIFF_ANION,
    DIFF_CATION,
    EPSILON_0,
    FARADAY,
    L_NM,
    NR,
    NZ,
    REL_PERMITTIVITY,
    V_T,
    annular_weights,
    make_grid,
)

import torch  # noqa: E402
import onnxruntime as ort  # noqa: E402

WEB = os.path.join(ROOT, "web_simulator")
WEB_DATA = os.path.join(WEB, "data")
WEB_MODELS = os.path.join(WEB, "models")
META_PATH = os.path.join(WEB_DATA, "model_meta.json")

CKPTS = {
    "deeponet": os.path.join(ROOT, "results", "models",
                             "deeponet_reparam_data_plus_physics_seed42.pt"),
    "fno": os.path.join(ROOT, "results", "models",
                        "fno_reparam_seed42_300ep.pt"),
}
ONNX_FILES = {
    "deeponet": os.path.join(WEB_MODELS, "deeponet_reparam_seed42.onnx"),
    "fno": os.path.join(WEB_MODELS, "fno_reparam_seed42.onnx"),
}

# tensors the JS engine needs (skip fixed cosine/sine buffers: recomputed in JS)
KEEP_PREFIXES = ("norm.", "branch.", "trunk.", "bias", "lift.", "pointwise.",
                 "film.", "proj.", "spectral.")


def b64_bytes(path):
    with open(path, "rb") as fh:
        return base64.b64encode(fh.read()).decode("ascii")


def serialize_weights(ckpt):
    sd = ckpt["state_dict"]
    layout = []
    chunks = []
    offset = 0
    for name, t in sd.items():
        if name.startswith("grid_coords") or name.endswith(".z"):
            continue
        if not name.startswith(KEEP_PREFIXES):
            continue
        # skip spectral basis buffers (Cr/Sr/Cz/Sz) — rebuilt in JS
        if name.endswith((".Cr", ".Sr", ".Cz", ".Sz")):
            continue
        arr = t.detach().cpu().numpy().astype(np.float32).ravel()
        layout.append({"name": name, "shape": list(t.shape), "offset": offset,
                       "length": int(arr.size)})
        chunks.append(arr)
        offset += arr.size
    blob = np.concatenate(chunks) if chunks else np.zeros(0, dtype=np.float32)
    b64 = base64.b64encode(blob.astype("<f4").tobytes()).decode("ascii")
    return {
        "layout": layout,
        "blob_b64": b64,
        "n_floats": int(blob.size),
        "mode": ckpt["mode"],
        "kind": ckpt["kind"],
        "epochs": ckpt.get("epochs"),
        "size": ckpt["size"],
        "feat_mean": list(ckpt["stats"]["mean"]),
        "feat_std": list(ckpt["stats"]["std"]),
    }


def jdump(obj):
    return json.dumps(obj, separators=(",", ":"))


def onnx_reference(probes):
    ref = {"probes": [], "note": "ONNX Runtime CPU outputs; JS engine must match <1e-5."}
    sessions = {k: ort.InferenceSession(p, providers=["CPUExecutionProvider"])
                for k, p in ONNX_FILES.items()}
    for mu in probes:
        entry = {"mu": mu, "models": {}}
        x = np.array([mu], dtype=np.float32)
        for k, s in sessions.items():
            names = [o.name for o in s.get_outputs()]
            out = s.run(None, {s.get_inputs()[0].name: x})
            entry["models"][k] = {
                n: [float(f"{v:.7g}") for v in a.reshape(-1)]
                for n, a in zip(names, out)
            }
        ref["probes"].append(entry)
    return ref


def main():
    os.makedirs(WEB_DATA, exist_ok=True)
    meta = json.load(open(META_PATH))

    weights = {}
    for kind, path in CKPTS.items():
        ckpt = torch.load(path, map_location="cpu", weights_only=False)
        weights[kind] = serialize_weights(ckpt)

    onnx_b64 = {k: b64_bytes(p) for k, p in ONNX_FILES.items()}

    bundle = {"meta": meta, "onnx": onnx_b64, "weights": weights}
    out_js = os.path.join(WEB_DATA, "embedded_bundle.js")
    with open(out_js, "w", encoding="utf-8") as fh:
        fh.write("/* auto-generated by scripts/build_web_bundle.py — do not edit */\n")
        fh.write("window.MODEL_BUNDLE = ")
        fh.write(jdump(bundle))
        fh.write(";\n")

    # probe reference for the DOM harness (covers in-dist, OOD, presets)
    probes = [
        [50.0, 100.0, -0.01, 5.0],     # benchmark #0
        [0.0, 100.0, 0.0, 5.0],        # symmetric
        [25.0, 50.0, -0.03, 4.0],      # generic in-box
        [-50.0, 200.0, -0.05, 8.0],    # train corner
        [70.0, 15.0, -0.08, 2.5],      # OOD voltage/salt/charge
        [-60.0, 30.0, -0.06, 7.0],     # OOD voltage
    ]
    ref = onnx_reference(probes)
    with open(os.path.join(WEB_DATA, "js_engine_reference.json"), "w") as fh:
        json.dump(ref, fh, separators=(",", ":"))

    print(f"wrote {out_js} ({os.path.getsize(out_js)} bytes)")
    print(f"deeponet weights: {weights['deeponet']['n_floats']} floats; "
          f"fno: {weights['fno']['n_floats']} floats")
    print("wrote js_engine_reference.json with", len(probes), "probes")


if __name__ == "__main__":
    main()
